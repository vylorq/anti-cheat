def width(text):
    return sum(len(G.get(ch, G[" "])[0]) + 1 for ch in text) - 1


def draw(img, x, y, text, colour, shadow=None, scale=1):
    """Draws text with a Minecraft-like 1px drop shadow (in scale units)."""
    px = img.load()

    def put(cx, cy, c):
        for dx in range(scale):
            for dy in range(scale):
                if 0 <= cx + dx < img.width and 0 <= cy + dy < img.height:
                    px[cx + dx, cy + dy] = c

    for layer, (ox, c) in enumerate([(1, shadow), (0, colour)]):
        if c is None:
            continue
        cx = x
        for ch in text:
            g = G.get(ch, G[" "])
            for gy, row in enumerate(g):
                for gx, v in enumerate(row):
                    if v == "#":
                        put(cx + (gx + ox) * scale, y + (gy + ox) * scale, c)
            cx += (len(g[0]) + 1) * scale
